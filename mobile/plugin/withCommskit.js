// Plugin

// Resolve @expo/config-plugins from the app, not from this file: when the kit is linked
// (`file:` / symlink), Node runs this file from its real path, where it isn't installed.
function loadConfigPlugins(config) {
  const roots = [config && config._internal && config._internal.projectRoot, process.cwd()].filter(Boolean);
  for (const root of roots) {
    try {
      return require(require.resolve("@expo/config-plugins", { paths: [root] }));
    } catch (e) {
      // try the next root
    }
  }
  return require("@expo/config-plugins");
}

function withCommskit(config, props) {
  const p = props || {};
  const { withAndroidManifest, withInfoPlist, withAppDelegate, withDangerousMod } = loadConfigPlugins(config);
  config = withAndroidManifest(config, (c) => {
    c.modResults = applyAndroidManifest(c.modResults, p);
    return c;
  });
  config = withInfoPlist(config, (c) => {
    c.modResults = applyInfoPlist(c.modResults, p);
    return c;
  });
  if (p.voip !== false) {
    config = withAppDelegate(config, (c) => {
      c.modResults.contents = addVoipToAppDelegate(c.modResults.contents, c.modResults.language);
      return c;
    });
    config = withDangerousMod(config, [
      "ios",
      async (c) => {
        const fs = require("fs");
        const path = require("path");
        const dir = path.join(c.modRequest.platformProjectRoot, c.modRequest.projectName || "");
        const header = fs.existsSync(dir) ? fs.readdirSync(dir).find((f) => f.endsWith("-Bridging-Header.h")) : null;
        if (!header) throw new Error("[commskit] no *-Bridging-Header.h found in " + dir);
        const file = path.join(dir, header);
        fs.writeFileSync(file, addBridgingHeaderImports(fs.readFileSync(file, "utf8")));
        return c;
      },
    ]);
  }
  return config;
}

module.exports = withCommskit;
module.exports.default = withCommskit;
module.exports.transforms = {
  addAndroidPermissions,
  addCallServices,
  applyAndroidManifest,
  applyInfoPlist,
  addVoipToAppDelegate,
  addBridgingHeaderImports,
};
module.exports.constants = { ANDROID_PERMISSIONS, IOS_BACKGROUND_MODES, MARK };
