/**
 * commskit Expo config plugin (plain CommonJS, runs at prebuild).
 *
 * Android: call / notification permissions, the react-native-callkeep ConnectionService and the
 * notifee foreground-service type (phoneCall|microphone, Android 14+).
 * iOS: UIBackgroundModes [audio, voip, remote-notification], microphone usage string, and the
 * Swift AppDelegate (Expo SDK 53+) PushKit code that reports VoIP pushes to CallKit synchronously
 * (required since iOS 13, otherwise iOS stops delivering VoIP pushes / kills the app).
 *
 * The transforms below are pure (object / string in, out) and idempotent (guarded by markers),
 * so they are unit-tested without Expo. @expo/config-plugins is required only when the plugin runs.
 *
 * notifee note: @notifee/react-native >= 7 ships its own Maven repo inside node_modules and wires it
 * through autolinking; on older setups add
 *   maven { url "$rootDir/../node_modules/@notifee/react-native/android/libs" }
 * to android/build.gradle allprojects.repositories.
 */

const ANDROID_PERMISSIONS = [
  "android.permission.RECORD_AUDIO",
  "android.permission.MODIFY_AUDIO_SETTINGS",
  "android.permission.POST_NOTIFICATIONS",
  "android.permission.USE_FULL_SCREEN_INTENT",
  "android.permission.FOREGROUND_SERVICE",
  "android.permission.FOREGROUND_SERVICE_PHONE_CALL",
  "android.permission.FOREGROUND_SERVICE_MICROPHONE",
  "android.permission.MANAGE_OWN_CALLS",
  "android.permission.VIBRATE",
  "android.permission.WAKE_LOCK",
];

const IOS_BACKGROUND_MODES = ["audio", "voip", "remote-notification"];
const DEFAULT_MIC_TEXT = "Allow $(PRODUCT_NAME) to use the microphone for voice calls.";

const CALLKEEP_SERVICE = "io.wazo.callkeep.VoiceConnectionService";
const CALLKEEP_MESSAGING_SERVICE = "io.wazo.callkeep.RNCallKeepBackgroundMessagingService";
const NOTIFEE_SERVICE = "app.notifee.core.ForegroundService";

const MARK = {
  import: "// @commskit-voip-import",
  register: "// @commskit-voip-register",
  begin: "// @commskit-voip-begin (generated by the commskit config plugin, do not edit)",
  end: "// @commskit-voip-end",
  headerBegin: "// @commskit-bridging-begin",
  headerEnd: "// @commskit-bridging-end",
};

// ---------------------------------------------------------------------------------------------
// Android (xml2js object from withAndroidManifest)

const nameOf = (node) => node && node.$ && node.$["android:name"];

function addAndroidPermissions(manifest, extra) {
  const root = manifest.manifest;
  const list = (root["uses-permission"] = root["uses-permission"] || []);
  for (const perm of ANDROID_PERMISSIONS.concat(extra || [])) {
    if (!list.some((p) => nameOf(p) === perm)) list.push({ $: { "android:name": perm } });
  }
  return manifest;
}

function addCallServices(manifest, options) {
  const opts = options || {};
  const root = manifest.manifest;
  root.$ = root.$ || {};
  const app = (root.application = root.application || [{ $: {} }])[0];
  const services = (app.service = app.service || []);
  const has = (name) => services.some((s) => nameOf(s) === name);
  if (opts.callKeepService !== false) {
    if (!has(CALLKEEP_SERVICE)) {
      services.push({
        $: {
          "android:name": CALLKEEP_SERVICE,
          "android:label": "Calls",
          "android:permission": "android.permission.BIND_TELECOM_CONNECTION_SERVICE",
          "android:foregroundServiceType": "phoneCall|microphone",
          "android:exported": "true",
        },
        "intent-filter": [{ action: [{ $: { "android:name": "android.telecom.ConnectionService" } }] }],
      });
    }
    if (!has(CALLKEEP_MESSAGING_SERVICE)) services.push({ $: { "android:name": CALLKEEP_MESSAGING_SERVICE } });
  }
  if (opts.notifeeForegroundService !== false && !has(NOTIFEE_SERVICE)) {
    root.$["xmlns:tools"] = root.$["xmlns:tools"] || "http://schemas.android.com/tools";
    services.push({
      $: {
        "android:name": NOTIFEE_SERVICE,
        "android:foregroundServiceType": "phoneCall|microphone",
        "tools:replace": "android:foregroundServiceType",
      },
    });
  }
  return manifest;
}

function applyAndroidManifest(manifest, props) {
  const p = props || {};
  addAndroidPermissions(manifest, p.androidPermissions);
  return addCallServices(manifest, p);
}

// ---------------------------------------------------------------------------------------------
// iOS Info.plist (object from withInfoPlist)

function applyInfoPlist(plist, props) {
  const p = props || {};
  const modes = new Set(plist.UIBackgroundModes || []);
  for (const m of p.voip === false ? ["audio", "remote-notification"] : IOS_BACKGROUND_MODES) modes.add(m);
  plist.UIBackgroundModes = Array.from(modes);
  if (p.microphonePermission) plist.NSMicrophoneUsageDescription = p.microphonePermission;
  else if (!plist.NSMicrophoneUsageDescription) plist.NSMicrophoneUsageDescription = DEFAULT_MIC_TEXT;
  return plist;
}

// ---------------------------------------------------------------------------------------------
// iOS AppDelegate.swift (string from withAppDelegate)

const VOIP_EXTENSION = [
  MARK.begin,
  "extension AppDelegate: PKPushRegistryDelegate {",
  "  public func pushRegistry(_ registry: PKPushRegistry, didUpdate pushCredentials: PKPushCredentials, for type: PKPushType) {",
  "    RNVoipPushNotificationManager.didUpdate(pushCredentials, forType: type.rawValue)",
  "  }",
  "",
  "  public func pushRegistry(_ registry: PKPushRegistry, didInvalidatePushTokenFor type: PKPushType) {}",
  "",
  "  // iOS 13+: every VoIP push MUST be reported to CallKit before this method returns.",
  "  public func pushRegistry(",
  "    _ registry: PKPushRegistry,",
  "    didReceiveIncomingPushWith payload: PKPushPayload,",
  "    for type: PKPushType,",
  "    completion: @escaping () -> Void",
  "  ) {",
  "    let raw = payload.dictionaryPayload",
  '    let data = (raw["data"] as? [AnyHashable: Any]) ?? raw',
  '    let callId = (data["call_id"] as? String) ?? UUID().uuidString',
  '    // uuid = uuid5(NAMESPACE_URL, "commskit:call:" + call_id), computed by the backend.',
  '    let uuid = (data["uuid"] as? String) ?? UUID().uuidString',
  '    let callerName = (data["caller_name"] as? String) ?? "Incoming call"',
  '    let handle = (data["caller_id"] as? String) ?? callId',
  '    let hasVideo = (data["call_type"] as? String) == "video"',
  "",
  "    RNVoipPushNotificationManager.didReceiveIncomingPush(with: payload, forType: type.rawValue)",
  "    RNCallKeep.reportNewIncomingCall(",
  "      uuid,",
  "      handle: handle,",
  '      handleType: "generic",',
  "      hasVideo: hasVideo,",
  "      localizedCallerName: callerName,",
  "      supportsHolding: false,",
  "      supportsDTMF: false,",
  "      supportsGrouping: false,",
  "      supportsUngrouping: false,",
  "      fromPushKit: true,",
  "      payload: data,",
  "      withCompletionHandler: completion",
  "    )",
  "  }",
  "}",
  MARK.end,
].join("\n");

const RETURN_SUPER = /^([ \t]*)return super\.application\(application, didFinishLaunchingWithOptions: launchOptions\)/m;

function addVoipToAppDelegate(contents, language) {
  if ((language || "swift") !== "swift") {
    throw new Error(
      "[commskit] the VoIP AppDelegate patch supports Swift AppDelegates (Expo SDK 53+). Add the PushKit code manually (see README) or pass { voip: false }.",
    );
  }
  let src = contents;
  if (!src.includes(MARK.import)) {
    if (/^import Expo[ \t]*$/m.test(src)) src = src.replace(/^import Expo[ \t]*$/m, (line) => line + "\nimport PushKit " + MARK.import);
    else src = "import PushKit " + MARK.import + "\n" + src;
  }
  if (!src.includes(MARK.register)) {
    if (!RETURN_SUPER.test(src)) {
      throw new Error("[commskit] could not find `return super.application(application, didFinishLaunchingWithOptions: launchOptions)` in AppDelegate.swift");
    }
    src = src.replace(RETURN_SUPER, (line, indent) => indent + "RNVoipPushNotificationManager.voipRegistration() " + MARK.register + "\n" + line);
  }
  const begin = src.indexOf(MARK.begin);
  if (begin >= 0) {
    const end = src.indexOf(MARK.end, begin);
    src = src.slice(0, begin) + VOIP_EXTENSION + src.slice(end + MARK.end.length);
  } else {
    src = src.replace(/\s*$/, "") + "\n\n" + VOIP_EXTENSION + "\n";
  }
  return src;
}

function addBridgingHeaderImports(contents) {
  if (contents.includes(MARK.headerBegin)) return contents;
  const block = [MARK.headerBegin, '#import "RNCallKeep.h"', '#import "RNVoipPushNotificationManager.h"', MARK.headerEnd].join("\n");
  return contents.replace(/\s*$/, "") + "\n\n" + block + "\n";
}

